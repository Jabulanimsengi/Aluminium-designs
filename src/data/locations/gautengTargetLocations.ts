export const gautengLocationMapBySlug = new Map<string, TargetLocation>(
  gautengTargetLocations.map(loc => [loc.slug, loc])
);

// Grouped by Municipality
export const getLocationsByMunicipality = (municipalityName: string): TargetLocation[] => {
  return gautengTargetLocations.filter(
    loc => loc.municipality.toLowerCase() === municipalityName.toLowerCase()
  );
};

// Grouped by Region (e.g. Soweto, Sandton, Centurion, East Rand, Vaal Triangle)
export const getLocationsByRegion = (regionName: string): TargetLocation[] => {
  return gautengTargetLocations.filter(
    loc => loc.region.toLowerCase() === regionName.toLowerCase()
  );
};

// Grouped by Category (e.g. Township Section, Suburb, Town, City Centre)
export const getLocationsByCategory = (categoryName: string): TargetLocation[] => {
  return gautengTargetLocations.filter(
    loc => loc.category.toLowerCase() === categoryName.toLowerCase()
  );
};
